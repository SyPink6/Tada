const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
module.exports=async({app,pet,panel,root,stamp,journal})=>{
 const errors=[];panel.webContents.on('console-message',(_event,_level,message)=>{if(message?.includes('Error'))errors.push(message);});
 const js=code=>panel.webContents.executeJavaScript(code);
 const wait=()=>new Promise(r=>setTimeout(r,300));
 const click=async text=>{await js(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)});if(!b)throw Error('Missing button: '+${JSON.stringify(text)});b.click();})()`);await wait();};
 await wait();
 assert.equal(pet.isVisible(),true);assert.equal(panel.isVisible(),false);
 await pet.webContents.executeJavaScript('window.tada.toggle()');await wait();assert.equal(panel.isVisible(),true);
 await click('整理作品集');await click('帮我找第一步');
 assert.match(await js('document.body.innerText'),/打开一个空白文档/);
 await click('就做这一步');await click('我分心了');
 assert.equal((await js('window.tada.load()')).task.status,'recovering');
 await panel.webContents.reload();await wait();await wait();assert.match(await js('document.body.innerText'),/接着做这一步/);
 await click('接着做这一步');await click('完成这一步');
 assert.equal((await js('window.tada.load()')).history.length,1);
 await js("document.querySelector('[aria-label=\"陪伴偏好\"]').click()");await wait();
 await js("document.querySelector('[aria-label=\"陪在窗口上方\"]').click()");await wait();assert.equal(pet.isAlwaysOnTop(),true);
 await click('回到小步');
 const shot=await panel.webContents.capturePage();await fs.writeFile(path.join(root,'work','native-panel-'+stamp+'.png'),shot.toPNG(),{flag:'wx'});
 await js('window.tada.collapse()');assert.equal(panel.isVisible(),false);assert.equal(pet.isVisible(),true);
 await js('window.tada.rest()');assert.equal(panel.isVisible(),false);assert.equal(pet.isVisible(),false);
 pet.showInactive();assert.equal(pet.isVisible(),true);
 await pet.webContents.executeJavaScript('window.tada.toggle()');await wait();assert.equal(panel.isVisible(),true);
 const lines=(await fs.readFile(journal,'utf8')).trim().split('\n');assert(lines.length>=5);assert.equal(JSON.parse(lines.at(-1)).history.length,1);
 assert.equal(panel.webContents.getLastWebPreferences().contextIsolation,true);assert.equal(panel.webContents.getLastWebPreferences().sandbox,true);
 const report={passed:true,electron:process.versions.electron,checks:['pet-only startup','click to expand','example task','start','recovery','reload restoration','completion persisted','always-on-top preference','collapse','rest to tray','restore','append-only journal','isolated renderer'],journalRecords:lines.length,errors};
 await fs.writeFile(path.join(root,'work','native-report-'+stamp+'.json'),JSON.stringify(report,null,2),{flag:'wx'});console.log('Native desktop checks passed:',JSON.stringify(report));app.quit();
};
